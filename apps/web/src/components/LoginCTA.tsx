export function LoginCTA({
  requireLogin,
  title = "QXwap"
}: {
  requireLogin: RequireLogin;
  text?: string;
  title?: string;
  action?: string;
}) {
  const content = getLoginCtaContent(title);

  return (
    <div className="empty value-empty login-cta-card">
      <b>{title}</b>
      <p>{content.summary}</p>
      <div className="step-list">
        {content.steps.map((step) => (
          <span key={step}>{step}</span>
        ))}
      </div>
      {content.note ? <small className="login-cta-note">{content.note}</small> : null}
      <button className="primary login-cta-button" onClick={() => requireLogin()}>
        {content.action ?? "เข้าสู่ระบบ"}
      </button>
    </div>
  );
}
